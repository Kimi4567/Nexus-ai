function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value && typeof value === 'object' && !Array.isArray(value))
}

function hasUsableObject(value: unknown): boolean {
  return isRecord(value) && Object.keys(value).length > 0
}

function hasText(value: unknown): boolean {
  return typeof value === 'string' && value.trim().length > 0
}

function hasUsableArray(value: unknown): boolean {
  return Array.isArray(value) && value.length > 0
}

function hasValidDate(value: string | Date | null | undefined): boolean {
  if (!value) return false
  const date = value instanceof Date ? value : new Date(value)
  return !Number.isNaN(date.getTime())
}

export function hasStrategyEvidence(aiOutput: unknown): boolean {
  if (!isRecord(aiOutput)) return false
  if (hasUsableObject(aiOutput.strategy)) return true

  const directKeys = [
    'contentPillars',
    'keyMessage',
    'coreMessage',
    'primaryOffer',
    'positioning',
    'businessObjective',
    'weeklyPlan',
    'weeklyExecutionPlan',
  ]

  return directKeys.some((key) => {
    const value = aiOutput[key]
    return hasText(value) || hasUsableArray(value) || hasUsableObject(value)
  })
}

function strategyReviewPassed(aiOutput: unknown): boolean {
  if (!isRecord(aiOutput)) return false
  const review = aiOutput.sentinelReview
  return isRecord(review) && review.status === 'passed'
}

export function deriveCampaignOperatingState(input: CampaignOperatingInput): CampaignOperatingState {
  const posts = Array.isArray(input.posts) ? input.posts : []
  const status = String(input.campaign?.status ?? '').toUpperCase()
  const hasStrategy = hasStrategyEvidence(input.campaign?.aiOutput)
  const hasStrategyReview = strategyReviewPassed(input.campaign?.aiOutput)
  const workflowEnabled = Boolean(input.campaign?.autopilotEnabled || input.campaign?.autopilotActivatedAt)
  const pendingLearningCount = Math.max(0, Math.trunc(input.pendingLearningCount ?? 0))

  const counts = {
    totalPosts: posts.length,
    draftPosts: 0,
    approvedPosts: 0,
    scheduledPosts: 0,
    autoScheduledPosts: 0,
    manualScheduledPosts: 0,
    publishedPosts: 0,
    apiPublishedPosts: 0,
    manualPublishedPosts: 0,
    analyticsReadyPosts: 0,
    failedPosts: 0,
    pendingGenerationPosts: 0,
  }

  let malformedScheduledPosts = 0

  for (const post of posts) {
    const postStatus = String(post.status ?? '').toUpperCase()
    const generationStatus = String(post.generationStatus ?? '').toUpperCase()
    const publishMode = String(post.publishMode ?? 'MANUAL').toUpperCase()
    const hasScheduledAt = hasValidDate(post.scheduledAt)
    const hasPublishedAt = hasValidDate(post.publishedAt)
    const hasPlatformRef = Boolean(post.platformPostId || post.platformUrl)
    const hasAnalytics = Boolean(post.analyticsData || post.analyticsFetched)

    if (postStatus === 'DRAFT') counts.draftPosts += 1
    if (postStatus === 'APPROVED') counts.approvedPosts += 1
    if (postStatus === 'FAILED') counts.failedPosts += 1
    if (['PENDING', 'GENERATING', 'AWAITING_UPLOAD'].includes(generationStatus)) {
      counts.pendingGenerationPosts += 1
    }

    if (postStatus === 'SCHEDULED') {
      if (hasScheduledAt) {
        counts.scheduledPosts += 1
        if (publishMode === 'AUTO') counts.autoScheduledPosts += 1
        else counts.manualScheduledPosts += 1
      } else {
        malformedScheduledPosts += 1
      }
    }

    if (postStatus === 'PUBLISHED' && hasPublishedAt) {
      counts.publishedPosts += 1
      if (hasPlatformRef) counts.apiPublishedPosts += 1
      if (hasValidDate(post.manuallyPublishedAt) || !hasPlatformRef) counts.manualPublishedPosts += 1
      if (hasAnalytics) counts.analyticsReadyPosts += 1
    }
  }

  const truthFlags = {
    hasStrategy,
    hasContentPlan: counts.totalPosts > 0,
    hasDraftContent: counts.draftPosts > 0,
    hasApprovedContent: counts.approvedPosts > 0,
    hasScheduledContent: counts.scheduledPosts > 0,
    hasAutoScheduledContent: counts.autoScheduledPosts > 0,
    hasPublishedContent: counts.publishedPosts > 0,
    hasApiPublishedContent: counts.apiPublishedPosts > 0,
    hasManualPublishedContent: counts.manualPublishedPosts > 0,
    hasAnalyticsData: counts.analyticsReadyPosts > 0,
    hasPendingLearning: pendingLearningCount > 0,
    workflowEnabled,
    autoPublishEnabled: counts.autoScheduledPosts > 0,
  }

  const blockers: string[] = []
  if (!hasStrategy) blockers.push('strategy')
  if (counts.totalPosts === 0) blockers.push('content_plan')
  if (counts.draftPosts > 0) blockers.push('content_review')
  if (malformedScheduledPosts > 0) blockers.push('scheduled_time')
  if (counts.publishedPosts > 0 && counts.analyticsReadyPosts === 0) blockers.push('analytics')
  if (pendingLearningCount > 0) blockers.push('learning_review')

  let stage: CampaignOperatingStage
  const pausedOrArchived = status === 'PAUSED' || status === 'ARCHIVED'

  if (truthFlags.hasPendingLearning) {
    stage = 'learning_review_needed'
  } else if (truthFlags.hasAnalyticsData) {
    stage = 'performance_ready'
  } else if (truthFlags.hasPublishedContent) {
    stage = 'published_waiting_for_analytics'
  } else if (truthFlags.autoPublishEnabled && truthFlags.workflowEnabled) {
    stage = 'auto_publish_enabled'
  } else if (truthFlags.hasAutoScheduledContent) {
    stage = 'scheduled_auto'
  } else if (truthFlags.hasScheduledContent) {
    stage = 'scheduled_manual'
  } else if (pausedOrArchived) {
    stage = 'paused_or_archived'
  } else if (!truthFlags.hasStrategy && truthFlags.hasContentPlan) {
    stage = 'content_review_needed'
    blockers.push('strategy_evidence_missing')
  } else if (!truthFlags.hasStrategy) {
    stage = 'strategy_missing'
  } else if (!hasStrategyReview && !truthFlags.hasContentPlan) {
    stage = 'strategy_review_needed'
  } else if (!truthFlags.hasContentPlan) {
    stage = 'content_plan_missing'
  } else if (truthFlags.hasDraftContent) {
    stage = 'content_review_needed'
  } else if (truthFlags.hasApprovedContent) {
    stage = 'content_approved_not_scheduled'
  } else {
    stage = 'strategy_review_needed'
  }

  const copy = STAGE_COPY[stage]
  return {
    stage,
    ...copy,
    blockers: Array.from(new Set(blockers)),
    counts,
    truthFlags,
  }
}
