export type CampaignStatusLike =
  | 'DRAFT'
  | 'ACTIVE'
  | 'SCHEDULED'
  | 'PAUSED'
  | 'COMPLETED'
  | 'ARCHIVED'
  | string

export type SocialPostStatusLike =
  | 'DRAFT'
  | 'APPROVED'
  | 'SCHEDULED'
  | 'PUBLISHED'
  | 'FAILED'
  | string

export type PublishModeLike = 'MANUAL' | 'AUTO' | string | null | undefined

export type CampaignOperatingStage =
  | 'strategy_missing'
  | 'strategy_review_needed'
  | 'content_plan_missing'
  | 'content_review_needed'
  | 'content_approved_not_scheduled'
  | 'scheduled_manual'
  | 'scheduled_auto'
  | 'auto_publish_enabled'
  | 'published_waiting_for_analytics'
  | 'performance_ready'
  | 'learning_review_needed'
  | 'paused_or_archived'

export interface CampaignOperatingInput {
  campaign?: {
    status?: CampaignStatusLike | null
    aiOutput?: unknown
    autopilotEnabled?: boolean | null
    autopilotActivatedAt?: string | Date | null
  } | null
  posts?: Array<{
    status?: SocialPostStatusLike | null
    generationStatus?: string | null
    scheduledAt?: string | Date | null
    approvedAt?: string | Date | null
    publishedAt?: string | Date | null
    manuallyPublishedAt?: string | Date | null
    publishMode?: PublishModeLike
    platformPostId?: string | null
    platformUrl?: string | null
    autoGenerated?: boolean | null
    analyticsData?: unknown
    analyticsFetched?: boolean | null
  }>
  pendingLearningCount?: number
}

export interface CampaignOperatingState {
  stage: CampaignOperatingStage
  stageLabel: string
  stageLabelAr: string
  stageHelper: string
  stageHelperAr: string
  primaryAction: {
    label: string
    labelAr: string
    href: string
  }
  blockers: string[]
  counts: {
    totalPosts: number
    draftPosts: number
    approvedPosts: number
    scheduledPosts: number
    autoScheduledPosts: number
    manualScheduledPosts: number
    publishedPosts: number
    apiPublishedPosts: number
    manualPublishedPosts: number
    analyticsReadyPosts: number
    failedPosts: number
    pendingGenerationPosts: number
  }
  truthFlags: {
    hasStrategy: boolean
    hasContentPlan: boolean
    hasDraftContent: boolean
    hasApprovedContent: boolean
    hasScheduledContent: boolean
    hasAutoScheduledContent: boolean
    hasPublishedContent: boolean
    hasApiPublishedContent: boolean
    hasManualPublishedContent: boolean
    hasAnalyticsData: boolean
    hasPendingLearning: boolean
    workflowEnabled: boolean
    autoPublishEnabled: boolean
  }
}

